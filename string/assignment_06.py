# Assignment 6: Explain string slicing

# Slicing extracts a portion of a string using the syntax: string[start:end]
# Start index is included, end index is excluded

text = "Python Programming"
print(f"String: {text}")
print(f"text[0:6] = {text[0:6]}")
print(f"text[7:18] = {text[7:18]}")
print(f"text[:6] = {text[:6]}")
print(f"text[7:] = {text[7:]}")
