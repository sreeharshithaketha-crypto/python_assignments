# Assignment 3: Explain string indexing

# Indexing allows access to individual characters in a string
# Python uses 0-based indexing (first character is at index 0)

text = "Python"
print(f"String: {text}")
print(f"Character at index 0: {text[0]}")
print(f"Character at index 2: {text[2]}")
print(f"Character at index 5: {text[5]}")
