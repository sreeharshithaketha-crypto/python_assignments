# Assignment 2: Explain different ways to create strings

# Single quotes
text1 = 'Python'

# Double quotes
text2 = "Python"

# Triple single quotes
text3 = '''Python
is powerful'''

# Triple double quotes
text4 = """Python
is easy"""

print(f"Single quotes: {text1}")
print(f"Double quotes: {text2}")
print(f"Triple quotes (single):\n{text3}")
print(f"Triple quotes (double):\n{text4}")
