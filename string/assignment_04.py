# Assignment 4: Explain positive indexing

# Positive indexing starts from left to right
# First character has index 0, second has index 1, and so on

text = "PYTHON"
print(f"String: {text}")
print(f"Index:  0  1  2  3  4  5")
print(f"Chars:  P  Y  T  H  O  N")
print()
print(f"text[0] = {text[0]}")
print(f"text[2] = {text[2]}")
print(f"text[4] = {text[4]}")
