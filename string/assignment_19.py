# Assignment 19: Explain count()

# count() method counts occurrences of a substring

text = "Python is easy. Python is powerful."
count = text.count("Python")

print(f"String: {text}")
print(f"Occurrences of 'Python': {count}")

# Count characters
text2 = "Mississippi"
print(f"\nString: {text2}")
print(f"Count 's': {text2.count('s')}")
print(f"Count 'i': {text2.count('i')}")
