# Assignment 23: Explain f-strings

# F-strings (formatted string literals) provide simple and readable formatting
# Variables and expressions can be included inside curly braces

name = "Ravi"
course = "Python"
a = 10
b = 20

print(f"{name} is learning {course}")
print(f"Total = {a + b}")

# Formatting decimals
price = 1234.56789
print(f"Price: {price:.2f}")
