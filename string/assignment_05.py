# Assignment 5: Explain negative indexing

# Negative indexing starts from right to left
# Last character has index -1, second last has index -2, and so on

text = "PYTHON"
print(f"String: {text}")
print(f"Index:  -6 -5 -4 -3 -2 -1")
print(f"Chars:   P  Y  T  H  O  N")
print()
print(f"text[-1] = {text[-1]}")
print(f"text[-2] = {text[-2]}")
print(f"text[-6] = {text[-6]}")
